"""Compose OpenCode agent permission lists from reusable fragments.

An agent source is a Markdown file whose YAML frontmatter has a `permissions:`
list. Any line of the form

    - include: shell-readonly

is replaced, in place, by the contents of `shell-readonly.yml` found on the
search path. Order is preserved exactly, so "last matching rule wins" behaves
the way the source reads.

    build.py [--path DIR ...] [--check] SRC_DIR OUT_DIR

--path   directory holding fragments (<name>.yml). Repeatable; earlier paths win,
         so a private directory can override or extend a public one.
         The directory containing this script's `permissions/` is always
         searched last.
--check  do not write; exit 1 if any output file is missing or out of date.

Only the standard library is required. If PyYAML is installed the result is
also validated (every rule needs action, resource and effect).
"""
import argparse
import pathlib
import re
import sys

INCLUDE = re.compile(r"^(?P<indent>\s*)-\s+include:\s*(?P<name>[A-Za-z0-9._-]+)\s*(?:#.*)?$")
HEADER = "# GENERATED by build.py from {src}. Do not edit; edit the source and fragments, then rebuild."


def find_fragment(name, paths):
    for p in paths:
        f = p / f"{name}.yml"
        if f.is_file():
            return f
    raise SystemExit(f"error: fragment '{name}' not found in: " + ", ".join(str(p) for p in paths))


def render_fragment(name, paths, indent):
    f = find_fragment(name, paths)
    out = [f"{indent}# >>> include {name}"]
    for line in f.read_text().splitlines():
        if INCLUDE.match(line):
            raise SystemExit(f"error: {f}: nested includes are not supported")
        out.append(f"{indent}{line}" if line.strip() else "")
    out.append(f"{indent}# <<< {name}")
    return out


def split_frontmatter(text, path):
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise SystemExit(f"error: {path}: no frontmatter")
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i], lines[i:]
    raise SystemExit(f"error: {path}: unterminated frontmatter")


def build_one(src, paths):
    front, rest = split_frontmatter(src.read_text(), src)
    out = [HEADER.format(src=src.name)]
    for line in front:
        m = INCLUDE.match(line)
        if m:
            out.extend(render_fragment(m["name"], paths, m["indent"]))
        else:
            out.append(line)
    return "---\n" + "\n".join(out) + "\n" + "\n".join(rest)


def validate(text, path):
    try:
        import yaml
    except ImportError:
        return
    front = text.split("---\n", 2)[1]
    data = yaml.safe_load(front)
    perms = data.get("permissions")
    if not isinstance(perms, list):
        raise SystemExit(f"error: {path}: `permissions` must be a list")
    for i, r in enumerate(perms):
        if not isinstance(r, dict) or set(r) != {"action", "resource", "effect"}:
            raise SystemExit(f"error: {path}: rule {i} must have exactly action, resource, effect: {r!r}")
        if r["effect"] not in ("allow", "ask", "deny"):
            raise SystemExit(f"error: {path}: rule {i} has invalid effect {r['effect']!r}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src", type=pathlib.Path)
    ap.add_argument("out", type=pathlib.Path)
    ap.add_argument("--path", action="append", default=[], type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    paths = a.path + [pathlib.Path(__file__).resolve().parent / "permissions"]
    sources = sorted(a.src.glob("*.md"))
    if not sources:
        raise SystemExit(f"error: no *.md sources in {a.src}")

    stale = []
    for s in sources:
        text = build_one(s, paths)
        validate(text, s)
        dest = a.out / s.name
        if a.check:
            if not dest.is_file() or dest.read_text() != text:
                stale.append(dest)
        else:
            a.out.mkdir(parents=True, exist_ok=True)
            dest.write_text(text)
            print(f"wrote {dest}")
    if stale:
        print("out of date: " + ", ".join(str(p) for p in stale), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
